/**
 * 驗證上傳之 CAD 設定檔 JSON 合法性
 */
export function validateCadProfile(raw: unknown): { valid: boolean; profile?: CADCustomProfile; error?: string } {
  if (!raw || typeof raw !== 'object') {
    return { valid: false, error: '上傳檔案不是有效的 JSON 物件格式' };
  }

  const obj = raw as Record<string, unknown>;

  if (!obj.profileName || typeof obj.profileName !== 'string') {
    return { valid: false, error: '設定檔缺少 `profileName` (樣式名稱) 欄位' };
  }

  if (!Array.isArray(obj.lineweights) || obj.lineweights.length === 0) {
    return { valid: false, error: '設定檔缺少 `lineweights` (線寬層級映射表) 或內容為空' };
  }

  if (!Array.isArray(obj.hatchSettings) || obj.hatchSettings.length === 0) {
    return { valid: false, error: '設定檔缺少 `hatchSettings` (預設填充線參數) 或內容為空' };
  }

  if (!Array.isArray(obj.blockLibrary) || obj.blockLibrary.length === 0) {
    return { valid: false, error: '設定檔缺少 `blockLibrary` (CAD 圖塊庫) 或內容為空' };
  }

  // 補齊預設值防呆
  const validatedProfile: CADCustomProfile = {
    profileId: typeof obj.profileId === 'string' ? obj.profileId : `custom_${Date.now()}`,
    profileName: String(obj.profileName),
    author: typeof obj.author === 'string' ? obj.author : '自訂設計師',
    version: typeof obj.version === 'string' ? obj.version : '1.0.0',
    description: typeof obj.description === 'string' ? obj.description : '使用者自訂 CAD 出圖樣式',
    updatedAt: new Date().toISOString().split('T')[0],
    lineweights: obj.lineweights.map((lw: any, idx: number) => ({
      id: lw.id || `lw-${idx}`,
      key: lw.key || 'cut_structural',
      label: lw.label || `自訂線條 ${idx + 1}`,
      layerName: lw.layerName || `LAYER_${idx + 1}`,
      colorIndex: Number(lw.colorIndex) || 7,
      colorHex: lw.colorHex || '#ffffff',
      lineWeightMm: Number(lw.lineWeightMm) || 0.25,
      lineType: lw.lineType || 'CONTINUOUS',
      description: lw.description || '',
    })),
    hatchSettings: obj.hatchSettings.map((ht: any, idx: number) => ({
      id: ht.id || `ht-${idx}`,
      targetMaterial: ht.targetMaterial || 'wood_joinery',
      label: ht.label || `填充材質 ${idx + 1}`,
      patternName: ht.patternName || 'ANSI31',
      angleDeg: Number(ht.angleDeg) ?? 45,
      spacingMm: Number(ht.spacingMm) || 2.0,
      lineWeightMm: Number(ht.lineWeightMm) || 0.13,
      layerName: ht.layerName || `HATCH_${idx + 1}`,
      colorIndex: Number(ht.colorIndex) || 6,
      colorHex: ht.colorHex || '#c084fc',
      description: ht.description || '',
    })),
    blockLibrary: obj.blockLibrary.map((blk: any, idx: number) => ({
      id: blk.id || `blk-${idx}`,
      blockName: blk.blockName || `BLOCK_${idx + 1}`,
      category: blk.category || 'elevation_tag',
      label: blk.label || `圖塊 ${idx + 1}`,
      symbolShape: blk.symbolShape || 'triangle_down',
      prefix: blk.prefix || '▼ FL+',
      scale: Number(blk.scale) || 1.0,
      layerName: blk.layerName || `BLOCK_${idx + 1}`,
      colorIndex: Number(blk.colorIndex) || 1,
      colorHex: blk.colorHex || '#ef4444',
      description: blk.description || '',
    })),
    sheetConfig: obj.sheetConfig && typeof obj.sheetConfig === 'object'
      ? {
          paperSize: (obj.sheetConfig as any).paperSize || 'A3',
          orientation: (obj.sheetConfig as any).orientation || 'LANDSCAPE',
          projectTitle: (obj.sheetConfig as any).projectTitle || '私邸室內裝修工程',
          drawingTitle: (obj.sheetConfig as any).drawingTitle || '固定80cm立面切圖放樣',
          drawingCode: (obj.sheetConfig as any).drawingCode || 'ID-A03',
          drawingScale: (obj.sheetConfig as any).drawingScale || '1:30',
          companyName: (obj.sheetConfig as any).companyName || '設計事務所',
          designerName: (obj.sheetConfig as any).designerName || '專案設計師',
        }
      : DEFAULT_CAD_PROFILE.sheetConfig,
  };

  return { valid: true, profile: validatedProfile };
}

/**
 * 下載 JSON 設定檔樣板，讓使用者可直接離線編輯或備份
 */
export function downloadProfileJson(profile: CADCustomProfile) {
  const jsonStr = JSON.stringify(profile, null, 2);
  const blob = new Blob([jsonStr], { type: 'application/json;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  const fileName = `CAD_PROFILE_${profile.profileId || 'custom'}_${new Date().toISOString().split('T')[0]}.json`;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
